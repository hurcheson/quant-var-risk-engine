"""
LaTeX Report Generator for Portfolio Risk & Monte Carlo Engine
Provides LaTeX mathematical expressions and generates standalone TeX reports.
"""

def get_gbm_latex() -> str:
    """Returns LaTeX equation string for Geometric Brownian Motion SDE and solution."""
    return r"dS_t = \mu S_t dt + \sigma S_t dW_t \implies S_T = S_0 \exp\left( \left(\mu - \frac{1}{2}\sigma^2\right)T + \sigma \sqrt{T} Z \right)"

def get_var_latex() -> str:
    """Returns LaTeX equation string for Value-at-Risk (VaR)."""
    return r"\text{VaR}_{\alpha}(L) = \inf \left\{ l \in \mathbb{R} : P(L \gt l) \le 1 - \alpha \right\} = \text{Percentile}(L, \alpha)"

def get_cvar_latex() -> str:
    """Returns LaTeX equation string for Conditional Value-at-Risk (CVaR / Expected Shortfall)."""
    return r"\text{CVaR}_{\alpha}(L) = \mathbb{E}\left[ L \mid L \ge \text{VaR}_{\alpha}(L) \right]"

class LaTeXReportGenerator:
    """Utility class to construct downloadable LaTeX (.tex) summary risk reports."""

    def __init__(self, sim_results: dict, portfolio_value: float):
        self.sim_results = sim_results
        self.portfolio_value = portfolio_value

    def generate_tex_document(self) -> str:
        """Generates a complete standalone LaTeX document string formatted for compilation."""
        conf_pct = int(self.sim_results.get("confidence_level", 0.95) * 100)
        horizon = self.sim_results.get("time_horizon_days", 1)
        simulations = self.sim_results.get("simulations", 10000)
        var_amt = self.sim_results.get("var_amount", 0.0)
        cvar_amt = self.sim_results.get("cvar_amount", 0.0)
        volatility = self.sim_results.get("volatility", 0.0)
        mean_return = self.sim_results.get("mean_return", 0.0)
        conf_level_val = self.sim_results.get("confidence_level", 0.95)

        tex_content = rf"""\documentclass{{article}}
\usepackage[utf8]{{utf8}}
\usepackage{{amsmath, amssymb, amsfonts}}
\usepackage{{geometry}}
\geometry{{margin=1in}}

\title{{\textbf{{Quantitative Portfolio Risk Analysis Report}}}}
\author{{Monte Carlo Risk Engine — Quantitative Analytics}}
\date{{\today}}

\begin{{document}}

\maketitle

\section{{Executive Summary}}
This document presents the risk analysis generated by the Monte Carlo Portfolio Risk Engine.
The simulation models portfolio asset dynamics under Geometric Brownian Motion (GBM).

\begin{{table}}[h!]
\centering
\begin{{tabular}}{{ll}}
\hline
\textbf{{Metric}} & \textbf{{Value}} \\ \hline
Initial Portfolio Value & \${self.portfolio_value:,.2f} \\
Confidence Level & {conf_pct}\% \\
Time Horizon & {horizon} Day(s) \\
Monte Carlo Iterations & {simulations:,} \\
Annualized Drift ($\mu$) & {mean_return * 252:.4f} \\
Daily Volatility ($\sigma$) & {volatility:.4f} \\ \hline
\textbf{{Monte Carlo VaR ({conf_pct}\%)}} & \textbf{{\${var_amt:,.2f}}} \\
\textbf{{Expected Shortfall (CVaR)}} & \textbf{{\${cvar_amt:,.2f}}} \\ \hline
\end{{tabular}}
\caption{{Quantitative Risk \& Monte Carlo Simulation Results}}
\end{{table}}

\section{{Mathematical Methodology}}

\subsection{{Geometric Brownian Motion (GBM)}}
Asset price evolution is modeled using the stochastic differential equation:
\begin{{equation}}
dS_t = \mu S_t dt + \sigma S_t dW_t
\end{{equation}}
The exact discrete solution over horizon $T$ is given by:
\begin{{equation}}
S_T = S_0 \exp\left( \left(\mu - \frac{{1}}{{2}}\sigma^2\right)T + \sigma \sqrt{{T}} Z \right), \quad Z \sim \mathcal{{N}}(0, 1)
\end{{equation}}

\subsection{{Value-at-Risk (VaR)}}
Value-at-Risk at confidence level $\alpha = {conf_level_val}$ represents the maximum expected loss over time horizon $T$:
\begin{{equation}}
\text{{VaR}}_{{\alpha}}(L) = \inf \left\{{ l \in \mathbb{{R}} : P(L > l) \le 1 - \alpha \right\}}
\end{{equation}}

\subsection{{Conditional Value-at-Risk (CVaR)}}
Expected Shortfall quantifies the expected loss given that loss exceeds the VaR threshold:
\begin{{equation}}
\text{{CVaR}}_{{\alpha}}(L) = \mathbb{{E}}\left[ L \mid L \ge \text{{VaR}}_{{\alpha}}(L) \right]
\end{{equation}}

\section{{Conclusion}}
For a portfolio value of \${self.portfolio_value:,.2f}, the estimated {conf_pct}\% {horizon}-day Value-at-Risk is \${var_amt:,.2f}, with an Expected Shortfall of \${cvar_amt:,.2f}.

\end{{document}}
"""
        return tex_content
